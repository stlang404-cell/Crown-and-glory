/** Renders docs/ENGINE_BENCHMARKS.md from tools/bench/results/*.json (numbers are never hand-typed). */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const R = (f: string) => { const u = new URL(`./results/${f}`, import.meta.url); return existsSync(u) ? JSON.parse(readFileSync(u, 'utf8')) : null; };
const speed = R('speed.json'), tactics = R('tactics.json'), abl = R('suite-ablation.json'), vsf = R('suite-vsfairy.json'), cal = R('suite-calibrate.json');
const extra = (f: string) => R(`suite-${f}.json`)?.summaries as S[] | undefined;
const browser = R('browser-speed.json');
const m4 = ['base40k-vs-fairy-n4k-m4-base', 'e4l0-vs-cur40k-m4-e1', 'e4l0-vs-cur40k-m4-e1r', 'e4l0T100-vs-curT100-m4-e1t', 'e4l25-vs-cur40k-m4-e1', 'futd-vs-cur40k-m4-x2', 'futd-vs-cur40k-m4-x2r', 'futd-vs-cur40k-m4-s1', 'lmr2-vs-cur40k-m4-x1', 'lmr2-vs-cur40k-m4-x1r', 'lmr2-vs-cur40k-m4-s1', 'ord-vs-cur40k-m4-x1', 'lmr2hg-vs-lmr2-m4-x2', 'ttb-vs-cur40k-m4-x1', 'prune-vs-cur40k-m4-x1', 'iirext-vs-cur40k-m4-x1', 'sing-vs-cur40k-m4-x2', 'curT100-vs-baseT100-m4-final', 'cur40k-vs-fairy-n4k-m4-final'].map(n => [`match-${n}.json`]);
const calib = JSON.parse(readFileSync(new URL('../../src/engine/calibration.json', import.meta.url), 'utf8'));
const tsuite = JSON.parse(readFileSync(new URL('./tactics.json', import.meta.url), 'utf8'));
const pct = (x: number) => (x * 100).toFixed(1) + '%';
type S = { a: string; b: string; games: number; wins: number; draws: number; losses: number; capped: number; illegal: number; score: number; scoreCI: [number, number]; eloDiff: number | null; eloCI: [number | null, number | null]; avgDepth: Record<string, number>; avgNodes: Record<string, number>; avgMs: Record<string, number> };
const table = (rows: S[]) => ['| A | B | Games | A W/D/L | Capped | Illegal | A score (95% pair-bootstrap) | Elo diff (CI) | A avg depth | B avg depth |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ...rows.map(s => `| ${s.a} | ${s.b} | ${s.games} | ${s.wins}/${s.draws}/${s.losses} | ${s.capped} | ${s.illegal} | ${pct(s.score)} (${pct(s.scoreCI[0])}–${pct(s.scoreCI[1])}) | ${s.eloDiff ?? '∞'} (${s.eloCI[0] ?? '−∞'} to ${s.eloCI[1] ?? '+∞'}) | ${s.avgDepth[s.a] ?? '—'} | ${s.avgDepth[s.b] ?? '—'} |`)].join('\n');
const env = (abl ?? speed)?.env ?? {};
let md = `# Engine benchmarks (measured)

All numbers in this file are generated by \`npx tsx tools/bench/report.ts\` from the raw JSON in
\`tools/bench/results/\`; per-game records are in the \`*-games.json\` files. Engine:
\`${env.searchId}\` + \`${env.evalId}\`. Host: ${env.cpu} (${env.cores} cores), ${env.platform}, Node ${env.node}.
These are Node.js measurements on a cloud Linux host — **not** browser, Windows or iPhone measurements.

Protocol: colour-swapped pairs over deterministic 2-ply openings (\`tools/bench/openings.json\`: all 100
two-ply openings filtered to |eval| ≤ 80 cp by Fairy-Stockfish depth 10 → 64 openings). Crown
adjudication (claims taken automatically, cap 300 plies counted separately as "capped", never as draws).
Score intervals: 95% bootstrap over opening pairs. Elo differences are internal logistic conversions of
the score, not FIDE or human ratings.

## Search speed

Fresh transposition table, 1,000 ms per search, 5 repetitions.

| Position | Median nodes/s | Min nodes/s | Median depth | Depth range |
| --- | --- | --- | --- | --- |
${(speed?.results ?? []).map((r: { fen: string; npsMedian: number; npsMin: number; depthMedian: number; depthRange: number[] }) => `| \`${r.fen}\` | ${r.npsMedian.toLocaleString('en')} | ${r.npsMin.toLocaleString('en')} | ${r.depthMedian} | ${r.depthRange.join('–')} |`).join('\n')}

## Tactical suite (independently verified)

${tsuite.count} positions where Fairy-Stockfish (depth 14, MultiPV 2) finds a unique best move (forced
mate, or ≥ 250 cp gap); ${tsuite.scanned} oracle positions scanned. Solved = Crown engine plays that move.

| Node budget | Solved | Rate |
| --- | --- | --- |
${Object.entries(tactics?.results ?? {}).map(([n, r]) => { const x = r as { solved: number; total: number; rate: number }; return `| ${Number(n).toLocaleString('en')} | ${x.solved}/${x.total} | ${pct(x.rate)} |`; }).join('\n')}

## Ablations (feature removed vs full engine, 40,000 nodes per move)

${abl ? table(abl.summaries) : '_not run_'}

Reading: a score above 50% for \`full40k\` means removing the feature hurt. Features whose interval
includes 50% (null move, aspiration windows) showed no measurable effect at this budget and were
retained because they did not hurt; this is not evidence that they help.

## Reference opponent: Fairy-Stockfish (development only)

Native build of commit 3a95e072 (\`losalamos\`, classical evaluation — no NNUE network exists for this
variant), 1 thread, 16 MB hash, \`go nodes N\`.

${vsf ? table(vsf.summaries) : '_not run_'}

These matches used crown-eval-2. Fairy-Stockfish is far more efficient per node; the Crown engine at
40k nodes scored between Fairy at 1k and 4k nodes. This is the honest measure of the gap.

## M2 engine experiments (40,000 nodes per move, 32 opening pairs unless noted)

Search experiments (crown-eval-2 baseline):

${extra('experiments') ? table(extra('experiments')!) : '_not run_'}

Held-out replication of the combined LMR-log + LMP result (openings 33–64, never used before):

${R('suite-confirm-lmr-lmp.json') ? table(R('suite-confirm-lmr-lmp.json').summaries) : '_not run_'}

The first-half +83 Elo did **not** replicate (0 Elo on held-out openings); neither feature was adopted.

Evaluation experiments (crown-eval-2 baseline):

${extra('evalexp') ? table(extra('evalexp')!) : '_not run_'}

Held-out replication of higher mobility weights (openings 33–64):

${extra('confirmmob') ? table(extra('confirmmob')!) : '_not run_'}

Adopted as **crown-eval-3** (mobility 6/5/3 instead of 4/3/2). Further step and second batch (crown-eval-3 baseline):

${extra('mobstep') ? table(extra('mobstep')!) : '_not run_'}

${extra('evalexp2') ? table(extra('evalexp2')!) : '_not run_'}

None of the second-batch changes was significant; they were not adopted.

### crown-eval-3 against the Fairy-Stockfish reference (re-run)

${extra('vsfairy3') ? table(extra('vsfairy3')!) : '_not run_'}

## Browser speed (production build, Chromium Web Worker)

${browser ? `${browser.browser}; ${browser.budget}.\n\n| Position | Plies played | Depth | Nodes | Engine ms | Nodes/s |\n| --- | --- | --- | --- | --- | --- |\n` + browser.results.map((r: { fen: string; plies: number; depth: number; nodes: number; engineMs: number; nps: number }) => `| \`${r.fen}\` | ${r.plies} | ${r.depth} | ${r.nodes.toLocaleString('en')} | ${r.engineMs} | ${r.nps.toLocaleString('en')} |`).join('\n') : '_not run_'}

## M4 (crown-search-2 + crown-eval-4 play engine; details in M4_ENGINE_STRENGTH.md)

Pre-M4 sections above were measured with the M3 engine and are kept as they were. M4 results (\`*-m4-*.json\`;
"cur40k" was crown-eval-3 in m4-x*/m4-e* runs and crown-eval-4 in m4-s1 runs):

${table(m4.map(([f]) => R(f)?.summary).filter(Boolean))}

Tactics, M4 play engine: ${Object.entries(R('tactics-m4-final.json')?.results ?? {}).map(([n, r]) => `${Number(n).toLocaleString('en')} nodes ${(r as { solved: number }).solved}/87`).join(', ')} (M3: ${Object.entries(R('tactics-m4-base.json')?.results ?? {}).map(([, r]) => (r as { solved: number }).solved).join(' / ')}).

## Strength levels and calibration

${cal ? table(cal.summaries) : '_not run_'}

Fitted ratings (\`src/engine/calibration.json\`, id \`${calib.id}\`): ${calib.method} ${calib.anchor}

| Level | Rating | RD (published) | Statistical SE | Calibration games |
| --- | --- | --- | --- | --- |
${(calib.levels ?? []).map((l: { level: number; rating: number; rd: number; se: number; games: number }) => `| L${l.level} | ${l.rating} | ${l.rd} | ${l.se} | ${l.games} |`).join('\n')}

Caveats: ${calib.caveats ?? ''}

## What is not claimed

No human-equivalent, FIDE, grandmaster or superhuman strength. No browser/iPhone/Windows speed numbers.
No claim that these levels map to human skill bands; human calibration requires human games (M2/M3).
`;
writeFileSync(new URL('../../docs/ENGINE_BENCHMARKS.md', import.meta.url), md);
