/** Writes docs/M2_ANALYSIS_CALIBRATION.md from tools/calibration/fit-results.json and the grade corpus. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const fit = JSON.parse(readFileSync(new URL('./fit-results.json', import.meta.url), 'utf8'));
const gradesFile = new URL('../../tests/fixtures/grades.json', import.meta.url);
const grades = existsSync(gradesFile) ? JSON.parse(readFileSync(gradesFile, 'utf8')) : null;
const M = fit.metrics as Record<string, { brier: number; brierCI: number[]; brierMinusP0CI: number[]; logloss: number; ece: number; reliability: { meanPred: number; meanOutcome: number; n: number }[] }>;
const f = (x: number, d = 4) => x.toFixed(d);
const names: Record<string, string> = { P0: 'P0 logistic s = 200 cp (current placeholder)', L1: 'L1 logistic, fitted s', L2: 'L2 logistic, fitted s + side-to-move intercept', ISO: 'ISO isotonic (PAV)' };
const best = Object.keys(M).sort((a, b) => M[a].brier - M[b].brier)[0];
const sig = M[best].brierMinusP0CI[1] < 0;
const decision = best !== 'P0' && sig
  ? `**${names[best]}** has the lowest held-out Brier score and its game-bootstrap interval for the Brier difference against P0 lies entirely below zero (${f(M[best].brierMinusP0CI[0], 5)} to ${f(M[best].brierMinusP0CI[1], 5)}).`
  : `No candidate beat the placeholder with an interval excluding zero (best: ${names[best]}).`;
const md = `# Analysis calibration (M2, Phase B)

Generated by \`npx tsx tools/calibration/report.ts\` from \`tools/calibration/fit-results.json\`.

## Question

Move grades and accuracy use an expected-outcome map u(cp) from engine evaluation to expected score.
v0 used the research placeholder u = 1/(1+e^(−cp/200)). Is a fitted map better on held-out 6×6 data?

## Corpus (\`tools/calibration/build_corpus.ts\`, id crown-calib-corpus-1)

- ${fit.corpus.games} benchmark games between near-equal Crown configurations (|measured Elo difference| < 75),
  so outcomes reflect positions rather than strength mismatches.
- Every 3rd ply from ply 6: ${fit.corpus.positions} positions scored by the Crown engine (depth ${fit.corpus.depth}, side-to-move view),
  labelled with the final result for the side to move (1 / ½ / 0). ${fit.corpus.cpPositions} centipawn-scored, ${fit.corpus.matePositions} mate-scored.
- Independence groups: ${fit.corpus.families.length} opening families (White's first move: ${fit.corpus.families.join(', ')}).
  **Leave-one-family-out cross-validation**: every position is predicted by a model fitted without its family.

## Held-out results

| Model | Brier (95% game-bootstrap) | Brier − P0 (95%) | Log loss | ECE (10 bins) |
| --- | --- | --- | --- | --- |
${Object.keys(M).map(k => `| ${names[k]} | ${f(M[k].brier, 5)} (${f(M[k].brierCI[0], 5)}–${f(M[k].brierCI[1], 5)}) | ${f(M[k].brierMinusP0CI[0], 5)} to ${f(M[k].brierMinusP0CI[1], 5)} | ${f(M[k].logloss)} | ${f(M[k].ece)} |`).join('\n')}

Full-data fits: L1 s = ${f(fit.fullFit.L1.s, 1)} cp; L2 s = ${f(fit.fullFit.L2.s, 1)} cp, intercept ${f(fit.fullFit.L2.a, 3)}.
Per-fold L1 scales: ${fit.foldParams.L1.map((p: { s: number }) => p.s.toFixed(0)).join(', ')} cp.

### Reliability (held-out, 10 equal-count bins)

| Bin | P0 predicted → observed | L1 predicted → observed | ISO predicted → observed | n |
| --- | --- | --- | --- | --- |
${M.P0.reliability.map((r, i) => `| ${i + 1} | ${r.meanPred} → ${r.meanOutcome} | ${M.L1.reliability[i]?.meanPred} → ${M.L1.reliability[i]?.meanOutcome} | ${M.ISO.reliability[i]?.meanPred} → ${M.ISO.reliability[i]?.meanOutcome} | ${r.n} |`).join('\n')}

### Mate scores

Positions with an engine mate score for the side to move scored ${f(fit.mate.favourable.meanOutcome, 3)} on average (n = ${fit.mate.favourable.n});
mate against the side to move scored ${f(fit.mate.unfavourable.meanOutcome, 3)} (n = ${fit.mate.unfavourable.n}). This supports keeping mates outside the cp
map with u = 1 / 0 as specified, but these are engine-vs-engine conversions, not proofs.

## Decision

${decision}

${best !== 'P0' && sig ? `The analyser therefore publishes **crown-accuracy-v1**: logistic expected-score map with s = ${f(fit.fullFit.L1.s, 0)} cp (L1 full-data fit), applied to new reports only. Old v0 reports are untouched; the Lab never merges v0 and v1 reports.` : 'The analyser keeps v0 and continues to label accuracy experimental.'}

What remains experimental even after this fit:
- The data are engine-vs-engine games at ~40k nodes per move; human games may convert advantages differently.
- Grade bin boundaries (0.002 / 0.02 / 0.05 / 0.12 / 0.25) and accuracy k = 4 are **not** re-fitted — there is no
  human-labelled grade data to fit them against. They stay labelled experimental.
- Great/Brilliant remain heuristic, gated by stability, uniqueness and deeper verification.

## Grade regression corpus (Gate B)

${grades ? `\`tests/fixtures/grades.json\` (${grades.fixtures.length} fixtures, settings ${grades.settings}): real positions with real candidate moves analysed by the production analyser.
Labels covered: ${[...new Set(grades.fixtures.filter((x: { kind: string }) => x.kind === 'label').map((x: { grade: string }) => x.grade))].join(', ')}. Missing (no clean example found): ${grades.missing.length ? grades.missing.join(', ') : 'none'}.
Negative fixtures: forced single move → Best (forced): ${grades.negatives.forced}; best-move recapture → not Brilliant: ${grades.negatives.recapture}; unsound sacrifice → not Brilliant/Great: ${grades.negatives.unsound}.
\`tests/grades.corpus.test.ts\` re-analyses each fixture and requires the identical label. In addition, \`tests/analysis.test.ts\`
checks every boundary of every bin, Great/Brilliant gating, uncertainty labelling and mate handling on synthetic inputs.` : '_not generated_'}
`;
writeFileSync(new URL('../../docs/M2_ANALYSIS_CALIBRATION.md', import.meta.url), md);
console.log('written');
