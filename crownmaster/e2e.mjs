import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';
const browser = await chromium.launch({ executablePath:'/usr/bin/chromium', args:['--no-sandbox'] });
const context = await browser.newContext({ viewport:{width:1366,height:1000}, serviceWorkers:'allow' });
const page = await context.newPage(), errors = [], checks = [];
page.on('pageerror',e=>errors.push(e.message));
const url = process.argv[2] ?? 'http://127.0.0.1:4174/';
function ok(v,msg) { if(!v) throw new Error(msg); checks.push(msg); }
await page.goto(url);
await page.locator('.storage').getByText('Ready for offline use',{exact:false}).waitFor();
await page.evaluate(()=>navigator.serviceWorker.ready);
await page.reload();
await page.getByRole('button',{name:'Calculate Best Move'}).click();
await page.locator('.candidate').first().waitFor({timeout:15000});
await page.getByRole('button',{name:'Stop',exact:false}).click();
ok(await page.locator('.candidate').count()===3,'Worker computes 3 real candidates');
const candidates = await page.locator('.candidate').allTextContents();
await page.locator('.candidate').nth(1).click();
await page.getByRole('button',{name:'Next reply'}).click();
ok((await page.locator('.board-caption').textContent()).includes('Variation'),'Candidate variation explores resulting board');
await page.getByRole('button',{name:'Set up position'}).click();
await page.getByRole('button',{name:'Clear',exact:true}).click();
await page.getByRole('button',{name:'Apply position',exact:true}).click();
ok((await page.getByRole('alert').textContent()).includes('king'),'Invalid editor position reports missing kings');
await page.getByRole('button',{name:'Cancel',exact:true}).click();
await page.getByLabel('Position notation or game JSON').fill('k5/6/1K4/6/6/5R w - - 0 1');
await page.getByRole('button',{name:'Import text',exact:true}).click();
await page.getByLabel('Analysis time').selectOption('1000');
await page.getByRole('button',{name:'Calculate Best Move'}).click();
await page.waitForFunction(()=>document.querySelector('.candidate .move strong')?.textContent==='Rf6#');
ok(true,'Known mate in one is calculated in the browser');
await page.waitForFunction(()=>!document.querySelector('.stop'));
const game = {name:'Review test',initialFen:'rnqknr/pppppp/6/6/PPPPPP/RNQKNR w - - 0 1',setupMoves:[],moves:['c2c3','c5c4','e1f3','b6a4']};
await page.getByLabel('Position notation or game JSON').fill(JSON.stringify(game));
await page.getByRole('button',{name:'Import text',exact:true}).click();
await page.getByRole('button',{name:'Review entire game'}).click();
await page.waitForFunction(()=>document.querySelectorAll('.review-row').length===4,{},{timeout:30000});
ok(true,'Whole-game review produces four graded moves');
await page.locator('.review-row').first().getByRole('button',{name:'Best:',exact:false}).click();
await page.getByRole('button',{name:'Next reply'}).click();
ok(true,'Review alternative can be replayed');
await page.getByRole('button',{name:'Starting position',exact:true}).click();
await page.locator('[data-square="c2"]').click();
await page.locator('[data-square="c3"]').click();
ok((await page.locator('.board-caption').textContent()).includes('1 / 1'),'Tap-to-move records a legal move');
await page.getByRole('button',{name:'Starting position',exact:true}).click();
await page.getByLabel('Analysis time').selectOption('extended');
await page.getByRole('button',{name:'Calculate Best Move'}).click();
await page.locator('.candidate').first().waitFor();
await page.getByRole('button',{name:'Stop',exact:false}).click();
const stopped = await page.locator('.metrics').textContent();
await page.waitForTimeout(300);
ok(stopped===await page.locator('.metrics').textContent(),'Stop prevents stale progress updates');
mkdirSync('crownmaster/evidence',{recursive:true});
await page.screenshot({path:'crownmaster/evidence/desktop.png',fullPage:true});
for(const width of [375,390]) { await page.setViewportSize({width,height:844}); ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`No horizontal overflow at ${width}px`); await page.screenshot({path:`crownmaster/evidence/mobile-${width}.png`,fullPage:true}); }
await context.setOffline(true);
await page.reload();
await page.getByRole('button',{name:'Calculate Best Move'}).click();
await page.locator('.candidate').first().waitFor({timeout:10000});
await page.getByRole('button',{name:'Stop',exact:false}).click();
ok(true,'Offline reload and cached Web Worker calculate successfully');
ok(errors.length===0,'No browser runtime errors');
writeFileSync('crownmaster/evidence/browser-results.json',JSON.stringify({checks,candidates,errors,browser:await browser.version(),note:'Chromium responsive checks; physical iPhone Safari not tested.'},null,2));
console.log(JSON.stringify({checks,errors},null,2));
await browser.close();
