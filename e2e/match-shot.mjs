import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const [url, out, w = '1366', h = '900'] = process.argv.slice(2);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +w, height: +h } });
const errs = [];
p.on('pageerror', e => errs.push(String(e)));
p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto(url);
await p.getByRole('button', { name: 'White' }).click();
await p.getByRole('button', { name: /Start match/i }).click();
await p.waitForSelector('[data-square="c2"]');
await p.click('[data-square="c2"]');
await p.waitForTimeout(300);
await p.screenshot({ path: out.replace('.png', '-select.png') });
await p.click('[data-square="c3"]');
await p.waitForTimeout(2500);
await p.screenshot({ path: out });
console.log('errors:', errs);
await b.close();
